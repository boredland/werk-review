	<h1>Über uns</h1>

	<div class="content">
		<p class="lead">
			Dies ist das unkommerzielle Projekt eines Germanistik-Absolventen und leidenschaftlichen
			Liebhabers klassischer Literatur und eines Informatikers mit einem Engagement für frei
			zugängliche Kultur. Ziel dieses Projektes ist es, dass Leser im deutschsprachigen Raum die
			klassische Literatur mehr für sich entdecken.
		</p>
		<p>
			Diese Website bietet eine Übersicht ausgewählter klassischer Autoren und deren Werke, und
			leitet weiter auf zahlreiche unkommerzielle Angebote, über welche Werke direkt gemeinfrei als
			Text gelesen (Gutenberg-Projekt) oder als Hörbuch gehört (Librivox) werden können.
		</p>
		<p>
			Die Datenbank ist aufgebaut wie bereits existierende Datenbanken für Filme (imdb.com) und
			Musik (discogs.com). Zu einem bestimmten Autor lassen sich alle literarischen Werke finden und
			nach Bewertungen einstufen, bzw. ranken.
		</p>
		<p>
			Das hier vorliegende literaturwissenschaftliche „Werkeregister“ ist also nur ein Teil des
			Projektes. Der sehr viel wichtigere Teil ist, dass sich „Leseratten“ gegenseitig Literatur
			empfehlen: welche Werke lassen sich nach heutigem Geschmack noch genussvoll lesen?
		</p>
		<p>Empfiehlt anderen Lesern die Werke bitte so persönlich wie möglich.</p>
		<ul>
			<li>Wie fandet ihr den Schreibstil?</li>
			<li>Wie fandet ihr die Figuren in der Geschichte?</li>
			<li>Fandet ihr die Handlung spannend?</li>
			<li>Gab es für euch interessante philosophische Gedanken?</li>
			<li>Habt ihr durch das Werk etwas gelernt?</li>
		</ul>
		<p>
			Es ist nicht nötig andere Leser darauf hinzuweisen, dass hier „Ein ganz großes Werk“ vorliegt.
			Teilt lieber mit was EUCH bewegt hat. Auch vom Plot sollte nur so viel verraten werden, dass
			andere Leser noch überrascht werden können.
		</p>
		<p>
			Und nach dieser Einleitung: viel Spaß beim Schmökern und Bewerten. Nachfolgend findet ihr noch
			einige Infos über die Datenbank.
		</p>

		<h2>Was ist klassische Literatur?</h2>
		<p>
			Der Begriff Klassik leitet sich vom lateinischen <em>classicus</em> ab und bedeutet
			ursprünglich „erstrangig“ oder „vorbildlich“. Heute bezeichnet er einerseits die deutsche
			Literaturepoche der Weimarer Klassik um Johann Wolfgang von Goethe und Friedrich Schiller,
			andererseits aber auch Werke von zeitloser Bedeutung und herausragender Qualität.
		</p>
		<p>
			Die in dieser Datenbank erfassten Werke beschränken sich nicht auf die Weimarer Klassik,
			sondern umfassen die gesamte klassische Literatur – von der Antike bis in die Moderne.
		</p>

		<h2>Woher kommen die Daten?</h2>
		<p>
			Die Datengrundlage liefert das Portal der deutschen Nationalbibliothek, bzw. diverse dort
			einsehbare Literaturlexika wie bspw. Kindlers Literatur Lexikon. Für internationale Autoren
			wurden allerdings auch Onlinequellen herangezogen.
		</p>

		<h2>Welche Autoren sind hier eingepflegt?</h2>
		<p>
			Diese Datenbank soll über die Jahre immer weiterwachsen. Den Start stellte eine Liste von 25
			Autoren dar, die ich selbst zusammengestellt habe. Jeder dieser 25 Autoren hat mindestens ein
			Werk geschrieben, dass ich gut bis sehr gut fand. Außer Goethe 😉 Der ist nur drin, weil er
			für viele die „Klassik“ repräsentiert.
		</p>

		<h2>Welche Werke sind hier eingepflegt?</h2>
		<p>
			Diese Website hat sich dem Genuss an ästhetisch schönen Texten verschrieben. Bis dato sind vor
			allem Romane und Erzählungen in die Datenbank eingepflegt, also fiktive Geschichten. Darüber
			hinaus sind noch Berichte mit aufgenommen, da Reiseberichte und Memoiren aus dem 19. Jh. so
			schön und nach heutigen Maßstäben „unglaublich“ sind. Theaterstücke (Dramen, Lustspiele, etc.)
			und Lyrik sind noch nicht in die Datenbank eingepflegt, werden aber noch folgen.
		</p>
		<p>
			Was vorerst nicht als Inhalt der Datenbank geplant ist, sind Essays, wissenschaftliche
			Artikel, politische Pamphlete, Kochbücher, Briefwechsel und was sonst noch an zusammenhangslosen
			Texten im Nachlass von gestorbenen Autoren gefunden wurde. Wenn allerdings eine erhöhte
			Nachfrage nach einem der eben aufgezählten Genres besteht, werden diese in Zukunft noch
			recherchiert, bzw. nachträglich eingepflegt.
		</p>
		<p>
			Außerdem sind lediglich Werke eingepflegt, die auf Deutsch übersetzt wurden. Das reduziert
			leider das Werkeregister der internationalen Autoren beträchtlich. Ich war selbst erstaunt, wie
			viele Werke nie übersetzt wurden.
		</p>

		<h2>Was bedeuten die Publikations-Angaben?</h2>
		<p>
			Für eine wissenschaftliche Analyse ist essentiell: In welcher Reihenfolge wurde was
			geschrieben? Folgende Zeitangaben finden Sie in der Datenbank:
		</p>
		<table class="date-legend">
			<thead>
				<tr>
					<th>Angabe</th>
					<th>Erklärung</th>
				</tr>
			</thead>
			<tbody>
				<tr>
					<td>1846</td>
					<td>
						Wenn von einem Werk lediglich bekannt ist, wann die Erstveröffentlichung war, dann steht
						nur eine Jahreszahl im Werk.
					</td>
				</tr>
				<tr>
					<td>1855-1859</td>
					<td>
						Die Angabe kann auch ein Zeitraum sein. Wenn durch die Analyse des Nachlasses bekannt
						ist, dass ein Autor schon Jahre vor der Veröffentlichung daran gearbeitet hat, dann ist
						ein Zeitraum angegeben. Ggf. wurde das Werk aber auch kapitelweise fortlaufend in einer
						Zeitschrift publiziert. In dem Fall ist der Zeitraum von der Publikation des ersten
						Kapitels bis zur Publikation des letzten Kapitels angegeben.
					</td>
				</tr>
				<tr>
					<td>1817/1818</td>
					<td>
						Steht ein Schrägstrich zwischen zwei Jahreszahlen, dann ist die Datenlage nicht
						eindeutig. Dann gibt es valide Quellen für das eine Jahr und das andere auch. In dem Fall
						werden hier beide Jahre angegeben. Diese Angabe gibt einem trotzdem eine gute Auskunft
						darüber, wann ungefähr das Werk veröffentlicht sein muss.
					</td>
				</tr>
			</tbody>
		</table>
		<p>
			Bei sich widersprechenden Angaben in meinen Recherchen, wurden die Angaben der deutschen
			Nationalbibliothek anderen Quellen vorgezogen.
		</p>
